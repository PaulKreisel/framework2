// Package agent implements the `ticket agent` subcommand: launching an AI
// agent (currently always `claude`) from a ticket's on-disk env folder, with
// the env's auto-managed context files regenerated on every launch.
package agent

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"

	"framework2/internal/dir"
)

// AgentCommand is the binary execed by Run. Exported as a var so future work
// can swap it (e.g. a per-ticket choice) without further plumbing.
var AgentCommand = "claude"

// AgentDefaultArgs are passed to AgentCommand on every iteration of the
// wrapper loop, before any relaunch-supplied args. Tests override this to
// substitute a shell script for the real claude.
var AgentDefaultArgs = []string{"--dangerously-skip-permissions"}

// autoGenMarker is the comment line that opens every regenerated file. The
// text is identical across markdown and JSONC so a reader can grep for it.
const autoGenMarker = "AUTO-GENERATED by `ticket agent` on launch."

// Run resolves the env folder for ticketID, regenerates the auto-managed
// context files (CLAUDE.md, .claude/settings.json), and then execs
// AgentCommand from inside the env folder in a loop: after each exit, if a
// [SignalFile] is present, the loop regenerates context and re-execs
// AgentCommand with `--continue` plus the signal's args appended. The env
// folder must already exist — use `ticket env <id>` first.
//
// While AgentCommand is running, its pid is recorded at <env>/[PIDFile] so
// [Relaunch] can target it.
func Run(db, beadsDir, ticketID string) error {
	if ticketID == "" {
		return errors.New("ticket id required")
	}
	if beadsDir == "" {
		return errors.New("BEADS_DIR not set: cannot derive env root")
	}
	envPath := filepath.Join(beadsDir, "envs", ticketID)
	info, err := os.Stat(envPath)
	if err != nil {
		if os.IsNotExist(err) {
			return fmt.Errorf("env folder does not exist for %s: %s (run `ticket env %s` first)", ticketID, envPath, ticketID)
		}
		return fmt.Errorf("stat env dir: %w", err)
	}
	if !info.IsDir() {
		return fmt.Errorf("env path is not a directory: %s", envPath)
	}

	sigPath := filepath.Join(envPath, SignalFile)
	pidPath := filepath.Join(envPath, PIDFile)
	// Drop any stale signal/pid file before starting; otherwise the very
	// first iteration would relaunch on a leftover from a prior session.
	_ = os.Remove(sigPath)
	_ = os.Remove(pidPath)

	var extraArgs []string
	for {
		if err := Regenerate(db, envPath, ticketID); err != nil {
			return fmt.Errorf("regenerate env context: %w", err)
		}
		argv := append(append([]string{}, AgentDefaultArgs...), extraArgs...)
		cmd := exec.Command(AgentCommand, argv...)
		cmd.Dir = envPath
		cmd.Stdin = os.Stdin
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		if err := cmd.Start(); err != nil {
			return err
		}
		if err := os.WriteFile(pidPath, []byte(strconv.Itoa(cmd.Process.Pid)+"\n"), 0o644); err != nil {
			_ = cmd.Process.Kill()
			return fmt.Errorf("write pid file: %w", err)
		}
		waitErr := cmd.Wait()
		_ = os.Remove(pidPath)

		sigArgs, hasSignal, err := readSignal(sigPath)
		if err != nil {
			return err
		}
		if !hasSignal {
			return waitErr
		}
		extraArgs = append([]string{"--continue"}, sigArgs...)
	}
}

// Regenerate rewrites the env's auto-managed context files from the current
// state of the ticket and its linked dirs. Idempotent. Exported so tests can
// drive the regen step without forking AgentCommand.
func Regenerate(db, envPath, ticketID string) error {
	issue, err := loadIssue(db, ticketID)
	if err != nil {
		return err
	}
	dirs, err := dir.Load(db, ticketID)
	if err != nil {
		return err
	}
	if err := writeClaudeMD(envPath, issue, dirs); err != nil {
		return err
	}
	return writeSettings(envPath, dirs)
}

type bdIssue struct {
	ID          string `json:"id"`
	Title       string `json:"title"`
	Description string `json:"description"`
}

func loadIssue(db, ticketID string) (*bdIssue, error) {
	args := []string{}
	if db != "" {
		args = append(args, "--db", db)
	}
	args = append(args, "--json", "show", ticketID)
	out, err := exec.Command("bd", args...).Output()
	if err != nil {
		if ee, ok := err.(*exec.ExitError); ok && len(ee.Stderr) > 0 {
			return nil, fmt.Errorf("bd show %s: %v: %s", ticketID, err, ee.Stderr)
		}
		return nil, fmt.Errorf("bd show %s: %w", ticketID, err)
	}
	var rows []bdIssue
	if err := json.Unmarshal(out, &rows); err != nil {
		return nil, fmt.Errorf("parse bd show output for %s: %w", ticketID, err)
	}
	if len(rows) == 0 {
		return nil, fmt.Errorf("ticket not found: %s", ticketID)
	}
	return &rows[0], nil
}

func writeClaudeMD(envPath string, issue *bdIssue, dirs []dir.Entry) error {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- %s -->\n\n", autoGenMarker)
	fmt.Fprintf(&b, "# Ticket %s — %s\n\n", issue.ID, issue.Title)

	if issue.Description != "" {
		b.WriteString("## Description\n\n")
		b.WriteString(strings.TrimRight(issue.Description, "\n"))
		b.WriteString("\n\n")
	}

	b.WriteString("## Linked directories\n\n")
	if len(dirs) == 0 {
		b.WriteString("(none)\n\n")
	} else {
		for _, e := range dirs {
			fmt.Fprintf(&b, "- `%s`%s\n", e.Path, dirAnnotation(e))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Linking more directories into this session\n\n")
	b.WriteString("To gain access to a directory while staying in this session, link it\n")
	b.WriteString("then relaunch:\n\n")
	b.WriteString("- `this dir link <path>` — register an existing dir, or\n")
	b.WriteString("- `this dir worktree <bare-repo>` — create a worktree and register it.\n")
	b.WriteString("- `this agent relaunch` — wrapper re-execs claude with `--continue` and\n")
	b.WriteString("  the refreshed `additionalDirectories`. Extra args after `relaunch`\n")
	b.WriteString("  are appended to the claude command.\n\n")

	return os.WriteFile(filepath.Join(envPath, "CLAUDE.md"), []byte(b.String()), 0o644)
}

func dirAnnotation(e dir.Entry) string {
	var parts []string
	if e.Branch != "" {
		parts = append(parts, "branch: "+e.Branch)
	}
	if e.Repo != "" {
		parts = append(parts, "repo: "+e.Repo)
	} else if e.LocalRepo != "" {
		parts = append(parts, "local repo: "+e.LocalRepo)
	}
	if len(parts) == 0 {
		return ""
	}
	return " (" + strings.Join(parts, ", ") + ")"
}

// SettingsPayload mirrors the .claude/settings.json structure we write.
// Exported so tests can decode it without redeclaring the schema.
type SettingsPayload struct {
	Permissions struct {
		AdditionalDirectories []string `json:"additionalDirectories"`
	} `json:"permissions"`
}

func writeSettings(envPath string, dirs []dir.Entry) error {
	settingsDir := filepath.Join(envPath, ".claude")
	if err := os.MkdirAll(settingsDir, 0o755); err != nil {
		return fmt.Errorf("create .claude dir: %w", err)
	}
	paths := make([]string, 0, len(dirs))
	for _, e := range dirs {
		paths = append(paths, e.Path)
	}
	var payload SettingsPayload
	payload.Permissions.AdditionalDirectories = paths
	body, err := json.MarshalIndent(payload, "", "  ")
	if err != nil {
		return fmt.Errorf("marshal settings: %w", err)
	}
	body = append(body, '\n')
	return os.WriteFile(filepath.Join(settingsDir, "settings.json"), body, 0o644)
}
