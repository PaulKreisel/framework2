package pde

import (
	"fmt"
	"runtime"
	"strings"
)

// LaunchName is the name of the generated launch preset. `pde launch` with no
// argument picks the first entry, so the name only matters when a hand-added
// second preset needs selecting: `pde launch AP`.
const LaunchName = "AP"

// GeneratedMarker appears on the first line of every generated pde.yaml. Its
// absence is how [Write] recognizes a hand-written file it must not clobber.
const GeneratedMarker = "generated by `ticket pde`"

// knimeProductArgs identify the KNIME Analytics Platform product inside the
// resolved target platform.
const (
	knimeProduct     = "org.knime.product.KNIME_PRODUCT"
	knimeApplication = "org.knime.product.KNIME_APPLICATION"
	knimeSplash      = "org.knime.product"
)

// baseVMArgs is the KNIME AP launch preset, transcribed from a released AP's
// `knime.ini`. It lives in Go rather than in a template pde.yaml that generated
// files `includes:` because pde merges `launches` by name but REPLACES array
// values: an include can never append to a preset's vmArgs, only restate the
// whole list. Owning the list here makes Options.VMArgs a plain append.
//
// Omissions from knime.ini are deliberate: `-vm` (the JVM is chosen by pde via
