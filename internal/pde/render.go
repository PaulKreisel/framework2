// macVMArgs are required on macOS and invalid elsewhere. SWT's Cocoa backend
// must own the first thread, so without -XstartOnFirstThread the launched AP
// dies before showing a window.
var macVMArgs = []string{
	"-XstartOnFirstThread",
	"-Dorg.eclipse.swt.internal.carbon.smallFonts",
}

// Options is everything Render needs. All paths must be absolute and already
// tilde-expanded: pde performs no `~` expansion of its own.
type Options struct {
	// TicketID is recorded in the header comment only.
	TicketID string
	// Target is the `.target` definition path.
	Target string
	// BundlePool is the shared p2 artifact pool. Empty omits the key, leaving
	// pde's per-config default.
	BundlePool string
	// Bundles are the workspace bundle directories, in the order to emit.
	Bundles []Bundle
	// DataDir is the launched application's workspace. Empty leaves pde's
	// default, which is a fresh temporary directory per launch.
	DataDir string
	// VMArgs are appended after the built-in preset args.
	VMArgs []string
}

// Bundle is one `bundles:` entry plus the comment explaining where it came
// from, so a reader can tell a detected plugin from a configured extra.
type Bundle struct {
	Path string
	Note string
}

// Render produces the pde.yaml body.
//
// Notably absent: `target.p2Path` and `target.profileId`. Their defaults
// (`./.target/p2`, `profile`) resolve relative to the config file, so leaving
// them out gives every ticket an isolated p2 profile inside its own env folder
// while still sharing one bundle pool — download once, resolve per ticket.
func Render(o Options) []byte {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("# %s for bead %s.\n", GeneratedMarker, o.TicketID)
	p("#\n")
	p("# Re-running `ticket pde` overwrites this file, but only while this header is\n")
	p("# intact — delete or edit the first line and regeneration refuses to clobber it.\n")
	p("# Hand-editing is expected (extra bundles, extra vmArgs, a `tests:` block); see\n")
	p("# the `pde` skill. Machine-wide settings belong in <beadsDir>/project.yaml.\n")
	p("#\n")
	p("# `pde` finds this file by walking up from the working directory, so `pde compile`,\n")
	p("# `pde launch` and `pde test` work from this env folder and anywhere below it.\n")
	p("\n")

	p("target:\n")
	p("  definition: %s\n", yamlString(o.Target))
	if o.BundlePool != "" {
		p("  bundlePool: %s\n", yamlString(o.BundlePool))
	}
	p("\n")

	if len(o.Bundles) == 0 {
		p("# No changed plugins detected. `pde compile` has nothing to build until a bundle\n")
		p("# is added here (or a change is made and `ticket pde` re-run).\n")
		p("bundles: []\n")
	} else {
		p("bundles:\n")
	}
	for _, bundle := range o.Bundles {
		if bundle.Note != "" {
			p("  # %s\n", bundle.Note)
		}
		p("  - path: %s\n", yamlString(bundle.Path))
	}
	p("\n")

	p("launches:\n")
	p("  - name: %s\n", LaunchName)
	p("    product: %s\n", knimeProduct)
	p("    application: %s\n", knimeApplication)
	p("    splash: %s\n", knimeSplash)
	if o.DataDir != "" {
		p("    # Persistent AP workspace. Without it pde uses a fresh temp dir per launch,\n")
		p("    # so workflows and preferences from the last run are gone. `pde launch --clean`\n")
		p("    # rebuilds the OSGi state when a stale workspace misbehaves.\n")
		p("    dataDir: %s\n", yamlString(o.DataDir))
	}
	p("    vmArgs:\n")
	for _, a := range VMArgs(o.VMArgs) {
		p("      - %s\n", yamlString(a))
	}
	return []byte(b.String())
}

// VMArgs returns the full vmArgs list for the generated preset: the built-in
// KNIME args for this OS, then extra.
func VMArgs(extra []string) []string {
	out := make([]string, 0, len(baseVMArgs)+len(macVMArgs)+len(extra))
	if runtime.GOOS == "darwin" {
		out = append(out, macVMArgs...)
	}
	out = append(out, baseVMArgs...)
	return append(out, extra...)
}

// yamlString double-quotes a scalar. Generated values (absolute paths, JVM args
// containing `:` and `=`) are quoted unconditionally rather than case-by-case,
// so no path with a space or leading `-` can change the document's shape.
func yamlString(s string) string {
	escaped := strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s)
	return `"` + escaped + `"`
}
